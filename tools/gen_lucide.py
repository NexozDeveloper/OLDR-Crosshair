#!/usr/bin/env python3
"""Regenerates src/lucide_icons.h from the official `lucide-static` npm package.

    npm pack lucide-static && tar xzf lucide-static-*.tgz
    python tools/gen_lucide.py package/icons src/lucide_icons.h

Only crosshair-style icons are listed on purpose.
"""
import re, sys, pathlib

ICONS = [  # (lucide id, display name)
    ("crosshair", "Crosshair"), ("locate", "Locate"), ("locate-fixed", "Locate Fixed"),
    ("target", "Target"), ("plus", "Plus"), ("circle-plus", "Circle Plus"),
    ("square-plus", "Square Plus"), ("circle-dot", "Circle Dot"), ("dot", "Dot"),
    ("circle", "Circle"), ("scan", "Scan"), ("focus", "Focus"),
    ("asterisk", "Asterisk"), ("x", "X"), ("circle-x", "Circle X"), ("square-dot", "Square Dot"),
]

src_dir, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
lines = [
    "// GENERATED by tools/gen_lucide.py - do not edit by hand.",
    "// Icons: Lucide (https://lucide.dev), ISC License - see THIRD_PARTY_NOTICES.md.",
    "#pragma once",
    "",
    "namespace oldr {",
    "struct IconDef { const char* id; const char* name; const char* body; };",
    "// `body` is the inner SVG markup of the official 24x24 Lucide icon.",
    "inline const IconDef kIcons[] = {",
]
for icon_id, name in ICONS:
    svg = (src_dir / f"{icon_id}.svg").read_text(encoding="utf-8")
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    inner = re.sub(r"\s+", " ", inner).strip().replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'    {{"{icon_id}", "{name}", "{inner}"}},')
lines += ["};", "inline constexpr int kIconCount = sizeof(kIcons) / sizeof(kIcons[0]);", "}  // namespace oldr", ""]
out.write_text("\n".join(lines), encoding="utf-8")
print("wrote", out)
